/**
 * Header forensics and authentication correlation.
 *
 * Two jobs:
 *  1. Build the ordered `HeaderField[]` the Header Forensics page renders — the
 *     six core RFC 5322 fields plus whichever notable headers are present —
 *     flagging fields that are themselves evidence: a Reply-To on a different
 *     domain, a Return-Path that does not match the From, a display name that
 *     embeds a different address, an implausible Date, a missing Message-ID.
 *  2. Produce the `AuthenticationSummary` (SPF/DKIM/DMARC verdicts + alignment).
 *     Verdicts are always *evaluated here*, never taken from the backend's status
 *     strings: the backend reports whether a policy is published, not whether the
 *     connecting address is authorised by it. What the backend does contribute is
 *     live-DNS discovery of records the offline intelligence set does not cover,
 *     which is folded in as evaluator input. See `definitiveBackendVerdict`.
 */

import {
  evaluateSpf,
  evaluateDmarc,
  isAligned,
  parseDkimSignature,
  parseDmarcRecord,
  definitiveBackendVerdict,
  firstRecord,
} from '@/lib/authEval';
import { addressOf, domainOf } from '@/lib/format';
import type { ParsedEmail } from '@/lib/emailParser';
import { header } from '@/lib/emailParser';
import type {
  AuthVerdict,
  AuthenticationCheck,
  AuthenticationSummary,
  DataOrigin,
  EmailMetadata,
  HeaderField,
  Severity,
} from '@/types';
import type { WireForensics } from '../wire';
import type { DomainRecord } from '../intel/domainDatabase';
import { NOT_PRESENT, escalate, orgOf, sameOrganisation } from './shared';

export interface HeaderAnomaly {
  name: string;
  severity: Severity;
  reason: string;
}

interface HeaderForensics {
  headers: HeaderField[];
  anomalies: HeaderAnomaly[];
}

/**
 * Headers beyond the core six that carry forensic weight when present, in
 * display order. Each is rendered only if the message actually contains it, so
 * the table never shows empty rows.
 */
const NOTABLE_HEADERS = [
  'Sender',
  'X-Original-Sender',
  'Authentication-Results',
  'Received-SPF',
  'X-Originating-IP',
  'X-Sender-IP',
  'X-Forwarded-For',
  'X-Mailer',
  'User-Agent',
  'X-Priority',
  'Importance',
  'X-Spam-Status',
  'X-Spam-Score',
  'List-Unsubscribe',
  'MIME-Version',
  'Content-Type',
];

/**
 * Mailer signatures that indicate the message was generated by a script rather
 * than a mail client or a managed platform. Legitimate bulk mail uses these too,
 * so this is corroborating context, not proof of anything on its own.
 */
const SCRIPTED_MAILER = /phpmailer|php-?mail|x-?php|python|perl|libcurl|curl\/|sendmail\s|mass\s*mail|bulk\s*mail|swiftmailer/i;

/**
 * Build the header table. `metadata` carries the recovered fields (Reply-To and
 * Return-Path come from the local parser, which the backend does not return).
 * `analyzedAt` anchors the Date plausibility check; `parsed` supplies the
 * notable-header rows.
 */
export function buildHeaderForensics(
  metadata: EmailMetadata,
  analyzedAt: string,
  parsed?: ParsedEmail,
): HeaderForensics {
  const anomalies: HeaderAnomaly[] = [];
  const fromDomain = domainOf(metadata.from);

  const fields: { name: string; value: string; anomaly?: HeaderAnomaly }[] = [
    { name: 'From', value: metadata.from || NOT_PRESENT },
    { name: 'Return-Path', value: metadata.returnPath ?? NOT_PRESENT },
    { name: 'Reply-To', value: metadata.replyTo ?? NOT_PRESENT },
    { name: 'To', value: metadata.to || NOT_PRESENT },
    { name: 'Subject', value: metadata.subject || NOT_PRESENT },
    { name: 'Date', value: metadata.date ?? NOT_PRESENT },
    { name: 'Message-ID', value: metadata.messageId ?? NOT_PRESENT },
  ];

  const record = (name: string, anomaly: HeaderAnomaly): void => {
    anomalies.push(anomaly);
    attach(fields, name, anomaly);
  };

  // A message with no usable From header cannot be attributed at all, and no
  // domain-based check below can run.
  if (!fromDomain) {
    record('From', {
      name: 'From',
      severity: 'HIGH',
      reason: metadata.from
        ? `The From header (${metadata.from}) contains no parseable domain, so the sender cannot be attributed or authenticated.`
        : 'No From header is present, so the message has no claimed sender to authenticate.',
    });
  }

  // A display name that embeds its own address is a direct spoofing attempt: the
  // recipient reads the address in the name and never sees the real one.
  const embedded = metadata.fromDisplayName?.match(/[\w.+-]+@[\w.-]+\.\w+/)?.[0]?.toLowerCase() ?? null;
  if (embedded && embedded !== addressOf(metadata.from).toLowerCase()) {
    record('From', {
      name: 'From',
      severity: 'HIGH',
      reason: `The display name embeds the address ${embedded}, but the message was actually sent by ${addressOf(metadata.from) || 'an unparseable address'}. Mail clients show the display name, so the recipient sees the embedded address instead of the real one.`,
    });
  }

  // Reply-To on a different organisation is a hallmark of BEC: the reply is
  // steered to attacker-controlled infrastructure while the From looks familiar.
  if (metadata.replyTo) {
    const replyDomain = domainOf(metadata.replyTo);
    if (replyDomain && fromDomain && !sameOrganisation(replyDomain, fromDomain)) {
      record('Reply-To', {
        name: 'Reply-To',
        severity: 'HIGH',
        reason: `Reply-To (${replyDomain}) resolves to a different organisation than From (${fromDomain}); replies would leave the apparent sender's domain.`,
      });
    }
  }

  // Return-Path (envelope sender) mismatch weakens SPF alignment and often
  // reveals the real sending infrastructure behind a spoofed From.
  if (metadata.returnPath) {
    const rpDomain = domainOf(metadata.returnPath);
    if (rpDomain && fromDomain && !sameOrganisation(rpDomain, fromDomain)) {
      record('Return-Path', {
        name: 'Return-Path',
        severity: 'MEDIUM',
        reason: `Envelope Return-Path (${rpDomain}) does not align with the visible From domain (${fromDomain}).`,
      });
    }
  }

  // Message-ID domain mismatch is a weaker signal but corroborates the others.
  if (metadata.messageId) {
    const midHost = metadata.messageId.match(/@([^>]+)>?/)?.[1]?.toLowerCase() ?? null;
    if (midHost && fromDomain && orgOf(midHost) && !sameOrganisation(midHost, fromDomain)) {
      record('Message-ID', {
        name: 'Message-ID',
        severity: 'LOW',
        reason: `Message-ID was issued by ${midHost}, which differs from the sender domain ${fromDomain}.`,
      });
    }
  } else {
    record('Message-ID', {
      name: 'Message-ID',
      severity: 'LOW',
      reason: 'No Message-ID header is present; legitimate MTAs almost always add one.',
    });
  }

  // Date plausibility. A timestamp ahead of acquisition means the sender's clock
  // was wrong or the header was forged; either way the chronology is unreliable.
  if (!metadata.date) {
    record('Date', {
      name: 'Date',
      severity: 'LOW',
      reason: 'No Date header is present, so the message cannot be placed on a timeline from its own metadata.',
    });
  } else {
    const sent = new Date(metadata.date).getTime();
    const received = new Date(analyzedAt).getTime();
    if (Number.isNaN(sent)) {
      record('Date', {
        name: 'Date',
        severity: 'LOW',
        reason: `The Date header (${metadata.date}) is not a valid RFC 5322 timestamp, which is unusual for mail produced by a standard client.`,
      });
    } else if (!Number.isNaN(received) && sent - received > 86_400_000) {
      record('Date', {
        name: 'Date',
        severity: 'MEDIUM',
        reason: `The Date header claims the message was sent more than a day after it was acquired for analysis, so the stated send time is not credible.`,
      });
    }
  }

  if (!metadata.subject) {
    record('Subject', {
      name: 'Subject',
      severity: 'INFO',
      reason: 'The message has no Subject header.',
    });
  }

  const notable = parsed ? collectNotableHeaders(parsed, fromDomain, anomalies) : [];

  const headers: HeaderField[] = [...fields, ...notable].map((field) =>
    field.anomaly
      ? { name: field.name, value: field.value, anomaly: { severity: field.anomaly.severity, reason: field.anomaly.reason } }
      : { name: field.name, value: field.value },
  );

  return { headers, anomalies };
}

/**
 * Rows for the notable headers actually present, flagging the two cases that are
 * themselves evidence: an envelope `Sender` on unrelated infrastructure, and a
 * scripted mailer signature.
 */
function collectNotableHeaders(
  parsed: ParsedEmail,
  fromDomain: string,
  anomalies: HeaderAnomaly[],
): { name: string; value: string; anomaly?: HeaderAnomaly }[] {
  const rows: { name: string; value: string; anomaly?: HeaderAnomaly }[] = [];

  for (const name of NOTABLE_HEADERS) {
    const value = header(parsed, name.toLowerCase());
    if (!value) continue;

    let anomaly: HeaderAnomaly | undefined;

    if (name === 'Sender' || name === 'X-Original-Sender') {
      const senderDomain = domainOf(value);
      if (senderDomain && fromDomain && !sameOrganisation(senderDomain, fromDomain)) {
        anomaly = {
          name,
          severity: 'MEDIUM',
          reason: `${name} names ${senderDomain}, which is a different organisation to the From domain (${fromDomain}). The message was submitted by infrastructure other than the apparent sender's.`,
        };
      }
    }

    if ((name === 'X-Mailer' || name === 'User-Agent') && SCRIPTED_MAILER.test(value)) {
      anomaly = {
        name,
        severity: 'MEDIUM',
        reason: `${name} reports "${value}", indicating the message was generated by a script rather than a mail client. Legitimate bulk mail also does this, so treat it as corroboration alongside the other findings.`,
      };
    }

    if (anomaly) anomalies.push(anomaly);
    rows.push(anomaly ? { name, value, anomaly } : { name, value });
  }

  return rows;
}

/**
 * Attach an anomaly to its row. A single row can attract more than one finding
 * (a From header can be both unparseable and carry a spoofed display name), and
 * the row can only show one, so the more severe wins.
 */
function attach(
  fields: { name: string; anomaly?: HeaderAnomaly }[],
  name: string,
  anomaly: HeaderAnomaly,
): void {
  const field = fields.find((entry) => entry.name === name);
  if (!field) return;
  if (!field.anomaly || escalate(field.anomaly.severity, anomaly.severity) === anomaly.severity) {
    field.anomaly = anomaly;
  }
}

